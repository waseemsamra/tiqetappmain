function isUiLanguage(value: string): value is UiLanguage {
  return (SUPPORTED_LANGUAGES as readonly string[]).includes(value);
}

/** Narrows an arbitrary cookie value to a language the catalog covers. */
export function normalizeUiLanguage(value: string | undefined | null): UiLanguage {
  return value && isUiLanguage(value) ? value : 'en';
}

/**
 * Looks up `key` for `language`, substituting `{name}` placeholders from
 * `vars`. Falls back to English, then to the key itself, so a missing
 * translation never renders as an empty string.
 */
export function translate(
  language: string | undefined | null,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const lang = normalizeUiLanguage(language);
  const template = CATALOG[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
